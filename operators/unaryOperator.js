//A unary operator in JavaScript is an operator that performs an operation on a single operand (a single variable, value, or expression).

//post increment -use value then add
let a=2;
console.log(a++); //o/p-2
console.log(a) // o/p- 3

//pre increment- add first then use
let x=6;
console.log(++x);

//post decrement - use value then sub
let y=8;
console.log(y--);
console.log(y);

//pre decrement - sub first ten use value
let z=10;
console.log(--z);

// example
let h=2;
let o=8;

console.log("s=",h++ + ++o);//2+9
console.log(--o + o--);//8+8

